-- Extend cosmetic equip with the two season-pass cosmetics.
create or replace function public.donation_equip_rpc(p_player_id uuid,p_item_id text)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
declare p public.players;
begin
  select * into p from public.players where id=p_player_id for update;
  if not found then return jsonb_build_object('error','Игрок не найден'); end if;
  if p_item_id='default' then
    update public.players set profile_frame='',profile_background='' where id=p_player_id returning * into p;
  elsif p_item_id in ('frame_test','frame_amber','frame_route') and p_item_id=any(coalesce(p.owned_cosmetics,'{}')) then
    update public.players set profile_frame=p_item_id where id=p_player_id returning * into p;
  elsif p_item_id in ('background_concrete','background_brick','background_panelka','background_night_route')
    and p_item_id=any(coalesce(p.owned_cosmetics,'{}')) then
    update public.players set profile_background=p_item_id where id=p_player_id returning * into p;
  else return jsonb_build_object('error','Сначала получи эту косметику'); end if;
  return jsonb_build_object('success',true,'player',jsonb_build_object('profile_frame',p.profile_frame,
    'profile_background',p.profile_background,'owned_cosmetics',p.owned_cosmetics));
end $$;

