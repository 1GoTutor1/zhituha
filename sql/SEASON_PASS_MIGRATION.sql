-- Four-week, 30-tier season pass with server-owned progress and profile badge showcase.
-- Apply after FAMILY_SYSTEM_MIGRATION.sql and the currently used profession,
-- daily-mission, donation, cosmetic, premium-pass and energy-removal migrations.
-- Run this last so its wrappers stay around work_rpc, sell_inventory_rpc,
-- finish_profession_cycle_rpc and equip.
-- Safe to rerun.

create table if not exists public.season_pass_seasons (
  season_no integer generated by default as identity primary key,
  season_name text not null default 'Городские маршруты',
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  active boolean not null default true,
  premium_cost integer not null default 99 check (premium_cost >= 0),
  check (ends_at > starts_at)
);

create unique index if not exists season_pass_one_active_season
  on public.season_pass_seasons(active) where active;

create table if not exists public.season_pass_player_state (
  player_id uuid not null references public.players(id) on delete cascade,
  season_no integer not null references public.season_pass_seasons(season_no) on delete cascade,
  xp integer not null default 0 check (xp >= 0),
  premium_unlocked boolean not null default false,
  claimed_free integer[] not null default '{}',
  claimed_premium integer[] not null default '{}',
  earned_badges text[] not null default '{}',
  work_date date,
  work_count smallint not null default 0,
  sale_date date,
  sale_count smallint not null default 0,
  profession_date date,
  profession_count smallint not null default 0,
  updated_at timestamptz not null default clock_timestamp(),
  primary key (player_id, season_no)
);

alter table public.players
  add column if not exists season_badge_showcase text[] not null default '{}';

alter table public.season_pass_seasons enable row level security;
alter table public.season_pass_player_state enable row level security;
revoke all on public.season_pass_seasons, public.season_pass_player_state from public, anon, authenticated;
grant all on public.season_pass_seasons, public.season_pass_player_state to service_role;

create or replace function public.season_pass_ensure_current()
returns public.season_pass_seasons
language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
declare s public.season_pass_seasons; pass_start timestamptz;
begin
  select * into s from public.season_pass_seasons
    where active and ends_at > clock_timestamp() order by season_no desc limit 1;
  if found then return s; end if;

  perform pg_advisory_xact_lock(hashtext('zhituha-season-pass'));
  select * into s from public.season_pass_seasons
    where active and ends_at > clock_timestamp() order by season_no desc limit 1;
  if found then return s; end if;

  update public.season_pass_seasons set active=false where active;
  -- The first pass opens exactly when the currently running family season ends.
  -- If no active family season exists, start immediately as a safe fallback.
  perform public.family_ensure_current_season();
  select fs.ends_at into pass_start from public.family_seasons fs
    where fs.finalized_at is null and fs.ends_at > clock_timestamp()
    order by fs.season_no desc limit 1;
  pass_start:=coalesce(pass_start,clock_timestamp());
  insert into public.season_pass_seasons(season_name,starts_at,ends_at,active)
    values ('Городские маршруты',pass_start,pass_start+interval '28 days',true)
    returning * into s;
  return s;
end $$;

-- If this migration is reapplied after an earlier preview initialized the pass,
-- move its opening to the same family-season boundary without deleting rewards.
do $$
declare family_end timestamptz;
begin
  perform public.family_ensure_current_season();
  select fs.ends_at into family_end from public.family_seasons fs
    where fs.finalized_at is null and fs.ends_at > clock_timestamp()
    order by fs.season_no desc limit 1;
  if family_end is not null then
    update public.season_pass_seasons
    set starts_at=family_end,ends_at=family_end+interval '28 days'
    where active and starts_at>clock_timestamp() and starts_at<family_end and ends_at>clock_timestamp();
  end if;
end $$;

create or replace function public.season_pass_reward(p_level integer,p_track text)
returns jsonb language plpgsql immutable set search_path=pg_catalog,public,pg_temp as $$
begin
  if p_level not between 1 and 30 or p_track not in ('free','premium') then
    return jsonb_build_object('type','none','label','Награда');
  end if;
  if p_track='free' then
    if p_level=1 then return jsonb_build_object('type','money','amount',2000,'label','2 000 ₽'); end if;
    if p_level=15 then return jsonb_build_object('type','bundle','items',jsonb_build_array(
      jsonb_build_object('type','money','amount',12000,'label','12 000 ₽'),
      jsonb_build_object('type','badge','id','season_local','name','Свой район','icon','☕'))); end if;
    if p_level=30 then return jsonb_build_object('type','bundle','items',jsonb_build_array(
      jsonb_build_object('type','money','amount',25000,'label','25 000 ₽'),
      jsonb_build_object('type','premium','amount',10,'label','10 жетонов'),
      jsonb_build_object('type','badge','id','season_district','name','Знаток города','icon','🧭'))); end if;
    return jsonb_build_object('type','money','amount',500+p_level*50,'label',(500+p_level*50)::text||' ₽');
  end if;

  if p_level=1 then
    return jsonb_build_object('type','cosmetic','id','frame_route','name','Рамка «Маршрут»','icon','🚦');
  elsif p_level=10 then
    return jsonb_build_object('type','bundle','items',jsonb_build_array(
      jsonb_build_object('type','money','amount',10000,'label','10 000 ₽'),
      jsonb_build_object('type','premium','amount',10,'label','10 жетонов')));
  elsif p_level=15 then
    return jsonb_build_object('type','bundle','items',jsonb_build_array(
      jsonb_build_object('type','money','amount',25000,'label','25 000 ₽'),
      jsonb_build_object('type','premium','amount',15,'label','15 жетонов')));
  elsif p_level=20 then
    return jsonb_build_object('type','cosmetic','id','background_night_route','name','Фон «Ночной маршрут»','icon','🌃');
  elsif p_level=30 then
    return jsonb_build_object('type','bundle','items',jsonb_build_array(
      jsonb_build_object('type','money','amount',50000,'label','50 000 ₽'),
      jsonb_build_object('type','premium','amount',25,'label','25 жетонов'),
      jsonb_build_object('type','badge','id','season_route_master','name','Мастер маршрутов','icon','🏆')));
  end if;
  return jsonb_build_object('type','money','amount',750+p_level*50,'label',(750+p_level*50)::text||' ₽');
end $$;

create or replace function public.season_pass_state_rpc(p_player_id uuid)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
declare s public.season_pass_seasons; st public.season_pass_player_state; selected text[];
begin
  if not exists(select 1 from public.players where id=p_player_id) then
    return jsonb_build_object('error','Игрок не найден');
  end if;
  s:=public.season_pass_ensure_current();
  insert into public.season_pass_player_state(player_id,season_no)
    values(p_player_id,s.season_no) on conflict do nothing;
  select * into st from public.season_pass_player_state
    where player_id=p_player_id and season_no=s.season_no;
  select coalesce(season_badge_showcase,'{}') into selected from public.players where id=p_player_id;
  return jsonb_build_object(
    'season',jsonb_build_object('number',s.season_no,'name',s.season_name,'starts_at',s.starts_at,
      'ends_at',s.ends_at,'seconds_left',greatest(0,floor(extract(epoch from (s.ends_at-clock_timestamp())))::integer),
      'is_open',clock_timestamp()>=s.starts_at,
      'seconds_until_start',greatest(0,floor(extract(epoch from (s.starts_at-clock_timestamp())))::integer),
      'premium_cost',s.premium_cost),
    'xp',st.xp,'tier',least(30,floor(st.xp/45.0)::integer),'xp_in_tier',mod(st.xp,45),
    'premium_unlocked',st.premium_unlocked,'claimed_free',st.claimed_free,
    'claimed_premium',st.claimed_premium,
    'earned_badges',(select coalesce(array_agg(distinct badges.badge),'{}') from public.season_pass_player_state all_states
      cross join lateral unnest(all_states.earned_badges) as badges(badge) where all_states.player_id=p_player_id),
    'showcase',selected,'premium_balance',(select premium_balance from public.players where id=p_player_id),
    'tiers',(select jsonb_agg(jsonb_build_object('level',n,'required_xp',n*45,
       'free',public.season_pass_reward(n,'free'),'premium',public.season_pass_reward(n,'premium')) order by n)
       from generate_series(1,30) n));
end $$;

create or replace function public.season_pass_add_xp(p_player_id uuid,p_action text)
returns void language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
declare s public.season_pass_seasons; st public.season_pass_player_state; today date:=timezone('UTC',clock_timestamp())::date; gain integer:=0;
begin
  if p_action not in ('work','sale','profession') then return; end if;
  s:=public.season_pass_ensure_current();
  if clock_timestamp()<s.starts_at then return; end if;
  insert into public.season_pass_player_state(player_id,season_no)
    values(p_player_id,s.season_no) on conflict do nothing;
  select * into st from public.season_pass_player_state
    where player_id=p_player_id and season_no=s.season_no for update;
  if p_action='work' then
    if st.work_date is distinct from today then st.work_date:=today; st.work_count:=0; end if;
    if st.work_count<5 then gain:=7; st.work_count:=st.work_count+1; end if;
  elsif p_action='sale' then
    if st.sale_date is distinct from today then st.sale_date:=today; st.sale_count:=0; end if;
    if st.sale_count<1 then gain:=10; st.sale_count:=st.sale_count+1; end if;
  else
    if st.profession_date is distinct from today then st.profession_date:=today; st.profession_count:=0; end if;
    if st.profession_count<1 then gain:=10; st.profession_count:=st.profession_count+1; end if;
  end if;
  if gain>0 then
    update public.season_pass_player_state set xp=xp+gain,work_date=st.work_date,work_count=st.work_count,
      sale_date=st.sale_date,sale_count=st.sale_count,profession_date=st.profession_date,
      profession_count=st.profession_count,updated_at=clock_timestamp()
      where player_id=p_player_id and season_no=s.season_no;
  end if;
end $$;

create or replace function public.season_pass_unlock_premium_rpc(p_player_id uuid)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
declare s public.season_pass_seasons; st public.season_pass_player_state; p public.players;
begin
  s:=public.season_pass_ensure_current();
  if clock_timestamp()<s.starts_at then
    return jsonb_build_object('error','Пропуск ещё закрыт','opens_at',s.starts_at);
  end if;
  select * into p from public.players where id=p_player_id for update;
  if not found then return jsonb_build_object('error','Игрок не найден'); end if;
  insert into public.season_pass_player_state(player_id,season_no) values(p_player_id,s.season_no) on conflict do nothing;
  select * into st from public.season_pass_player_state where player_id=p_player_id and season_no=s.season_no for update;
  if st.premium_unlocked then return jsonb_build_object('error','Премиум-дорожка уже открыта'); end if;
  if coalesce(p.premium_balance,0)<s.premium_cost then return jsonb_build_object('error','Недостаточно жетонов'); end if;
  update public.players set premium_balance=premium_balance-s.premium_cost where id=p_player_id returning * into p;
  update public.season_pass_player_state set premium_unlocked=true,updated_at=clock_timestamp()
    where player_id=p_player_id and season_no=s.season_no;
  return jsonb_build_object('success',true,'premium_balance',p.premium_balance);
end $$;

create or replace function public.season_pass_claim_rpc(p_player_id uuid,p_level integer,p_track text)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
declare s public.season_pass_seasons; st public.season_pass_player_state; reward jsonb; reward_item jsonb; p public.players;
begin
  if p_level is null or p_level not between 1 and 30 or p_track is null or p_track not in ('free','premium') then
    return jsonb_build_object('error','Неверная награда');
  end if;
  select * into p from public.players where id=p_player_id for update;
  if not found then return jsonb_build_object('error','Игрок не найден'); end if;
  s:=public.season_pass_ensure_current();
  if clock_timestamp()<s.starts_at then
    return jsonb_build_object('error','Пропуск ещё закрыт','opens_at',s.starts_at);
  end if;
  insert into public.season_pass_player_state(player_id,season_no) values(p_player_id,s.season_no) on conflict do nothing;
  select * into st from public.season_pass_player_state where player_id=p_player_id and season_no=s.season_no for update;
  if st.xp<p_level*45 then return jsonb_build_object('error','Сначала открой этот уровень'); end if;
  if p_track='premium' and not st.premium_unlocked then return jsonb_build_object('error','Сначала открой премиум-дорожку'); end if;
  if p_track='free' and p_level=any(st.claimed_free) then return jsonb_build_object('error','Награда уже получена'); end if;
  if p_track='premium' and p_level=any(st.claimed_premium) then return jsonb_build_object('error','Награда уже получена'); end if;
  reward:=public.season_pass_reward(p_level,p_track);
  if reward->>'type'='money' then
    update public.players set money=coalesce(money,0)+(reward->>'amount')::bigint where id=p_player_id returning * into p;
  elsif reward->>'type'='badge' then
    update public.season_pass_player_state set earned_badges=array(select distinct unnest(earned_badges||array[reward->>'id']))
      where player_id=p_player_id and season_no=s.season_no;
  elsif reward->>'type'='cosmetic' then
    update public.players set owned_cosmetics=array(select distinct unnest(coalesce(owned_cosmetics,'{}')||array[reward->>'id']))
      where id=p_player_id returning * into p;
  elsif reward->>'type'='bundle' then
    for reward_item in select value from jsonb_array_elements(reward->'items') loop
      if reward_item->>'type'='money' then
        update public.players set money=coalesce(money,0)+(reward_item->>'amount')::bigint where id=p_player_id;
      elsif reward_item->>'type'='premium' then
        update public.players set premium_balance=coalesce(premium_balance,0)+(reward_item->>'amount')::bigint where id=p_player_id;
      elsif reward_item->>'type'='badge' then
        update public.season_pass_player_state set earned_badges=array(
          select distinct unnest(earned_badges||array[reward_item->>'id']))
          where player_id=p_player_id and season_no=s.season_no;
      elsif reward_item->>'type'='cosmetic' then
        update public.players set owned_cosmetics=array(
          select distinct unnest(coalesce(owned_cosmetics,'{}')||array[reward_item->>'id'])) where id=p_player_id;
      end if;
    end loop;
    select * into p from public.players where id=p_player_id;
  end if;
  if p_track='free' then
    update public.season_pass_player_state set claimed_free=array_append(claimed_free,p_level),updated_at=clock_timestamp()
      where player_id=p_player_id and season_no=s.season_no;
  else
    update public.season_pass_player_state set claimed_premium=array_append(claimed_premium,p_level),updated_at=clock_timestamp()
      where player_id=p_player_id and season_no=s.season_no;
  end if;
  return jsonb_build_object('success',true,'reward',reward,'money',p.money,'premium_balance',p.premium_balance);
end $$;

create or replace function public.season_pass_select_badges_rpc(p_player_id uuid,p_badges text[])
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
declare requested text[]; owned text[];
begin
  requested:=coalesce(p_badges,'{}');
  if cardinality(requested)>3 or cardinality(requested)<>(select count(distinct u.value) from unnest(requested) as u(value)) then
    return jsonb_build_object('error','Выбери не больше трёх разных значков');
  end if;
  select coalesce(array_agg(distinct badge), '{}') into owned
  from public.season_pass_player_state st cross join lateral unnest(st.earned_badges) as badges(badge)
  where st.player_id=p_player_id and badges.badge=any(requested);
  if cardinality(owned)<>cardinality(requested) then return jsonb_build_object('error','Можно выбрать только полученные значки'); end if;
  update public.players set season_badge_showcase=requested where id=p_player_id;
  return jsonb_build_object('success',true,'showcase',requested);
end $$;

