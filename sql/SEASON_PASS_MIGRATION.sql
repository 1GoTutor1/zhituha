create or replace function public.work_rpc(p_player_id uuid)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,pg_temp as $$
declare r jsonb;
begin
  r:=public.work_rpc_before_season_pass(p_player_id);
  if r is null or r ? 'error' or coalesce((r->>'captcha_required')::boolean,false)
    or coalesce((r->>'blocked')::boolean,false) or coalesce((r->>'ignored')::boolean,false)
    or r->>'work_pay' is null then return r; end if;
  perform public.season_pass_add_xp(p_player_id,'work'); return r;
end $$;

